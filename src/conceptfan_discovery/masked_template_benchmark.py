"""V32 frozen TEST-only waveform deformation on new V31-family episodes.

A new episode draw (seed20261118) is generated by the existing pulse-order
synthetic simulator. The shape-drift intervention is performed only in
simulated TEST sensor readings. The generator-supplied hidden amplitude is
used ONLY to synthesize this physically defined malfunction; no model,
source proposer, template, gate or risk learner receives this amplitude.
"""
from __future__ import annotations

import numpy as np

from conceptfan_discovery.phase_pulse_benchmark_v31 import (
    device_environment,phase_pulse_world,
)

SEED=20261118
TRAIN_N,VALID_N,TEST_N=1500,1000,800
STRESS=("complete","MCAR20","MCAR40","MNAR","block8")
CASES=(
    ("healthy_physical","physical","benign","none"),
    ("known_physical_flip","physical","flip_physical","flip_physical"),
    ("known_recording_artifact_flip","artifact","flip_artifact","flip_artifact"),
    ("unseen_physical_flip","physical","benign","flip_physical"),
    ("complete_dictionary","complete","benign","none"),
    ("unseen_pulse_shape_drift","physical","benign","change_pulse_shape"),
)


def test_device_observations(x,case,*,oracle_pulse_amplitude_for_GENERATOR_ONLY):
    if case!="change_pulse_shape":
        return device_environment(x,case)
    original=np.asarray(x,dtype=np.float32)
    amp=np.asarray(oracle_pulse_amplitude_for_GENERATOR_ONLY,dtype=np.float32)
    if (original.ndim!=3 or original.shape[1:]!=(16,12)
        or len(amp)!=len(original)):
        raise ValueError("TEST only synthetic shape change has incompatible generator source")
    # Generate an alternate mean-zero pulse with an earlier change point.
    # Its source amplitude (and original label law) are unchanged.
    old=np.r_[np.ones(8),-np.ones(8)].astype(np.float32)
    new=np.r_[np.ones(3),np.full(13,-3./13.)].astype(np.float32)
    assert abs(float(new.mean()))<1e-7
    changed=original.copy()
    delta=amp[:,None,None]*(new-old)[None,:,None]
    changed[:,:,4:7]+=delta
    np.testing.assert_array_equal(changed[:,:,:4],original[:,:,:4])
    return changed


def own_draw(*,n_train=TRAIN_N,n_valid=VALID_N,n_test=TEST_N):
    return phase_pulse_world(
        seed=SEED,n_train=n_train,n_valid=n_valid,n_test=n_test)
