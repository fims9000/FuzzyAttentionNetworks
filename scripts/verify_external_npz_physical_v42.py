"""V42 end-to-end external ON/OFF NPZ inference parity on saved frozen data.

ONLY THIS QA HARNESS imports the synthetic generator to reproduce the
actual recorded test readouts. The deployed scripts/infer_physical_reference_v42.py
has NO generator, original H/S, TEST Y or TEST reference R dependency.

For 4 source devices × 4 fault worlds × 3 real missingness modes:
- save 12 genuinely observed ON and OFF sensor episodes in 48 strict
  NPZ data-only files, NaN payload everywhere mask=False;
- reopen the exact TRAIN/VALID calibrated trusted JSON reference source;
- run the same public per-episode NPZ->JSON user interface;
- check exact masks, selected pairs, anchored physical-reference values,
  refusal reasons and absence of fake physical estimates when OFF fails;
- compare against original, immutable TEST patient arrays generated by
  the separate original experiment code, max 1e-8 due float rounding.
"""
from __future__ import annotations
import argparse,json
from pathlib import Path
import numpy as np

from conceptfan_discovery.physical_reference_world_v42 import (
    generate_device_v42,render_observed_v42,masks_v42,
)
from scripts.infer_physical_reference_v42 import (
    inference_physical_reference_npz_v42,
)

CASES={
    "healthy_energy":("none","none"),
    "OFF_only_U4_drift":("off_drift","none"),
    "OFF_reference_unavailable":("no_reference","none"),
    "VALID2_known_OFF_drift":("off_drift","off_drift"),
}
# Compare against original frozen EXPERIMENT's named stress ordering,
# not the WORLD module's older 10-stress inventory. The RNG seed depends
# on this exact preregistered 7-stress order; previous incorrect QA lookup
# generated DIFFERENT physical missingness masks for missing_view_A.
REGISTERED_STRESS_ORDER=(
    "complete","MCAR20","MCAR40","MCAR50",
    "missing_view_A","missing_view_B","missing_view_C",
)
MASKS=("MCAR20","MCAR40","missing_view_A")


def qa(evidence:Path,out:Path):
    if out.exists():
        raise FileExistsError("Never overwrite user-path physical inference audit")
    d=json.loads((evidence/"STATUS.json").read_text())
    if d["status"]!="V42_PHYSICAL_REFERENCE_SEMANTIC_AUDIT_EXECUTED":
        raise ValueError("Must compare against completed frozen V42 TEST evidence")
    source=np.load(
        evidence/"FROZEN_TEST_MEASURED_SOURCE_AND_TRUTH_AUDIT.npz",
        allow_pickle=False)
    out.mkdir(parents=True,exist_ok=False)
    entries=[]
    max_error=0.
    for dev in d["devices"]:
        w=generate_device_v42(
            device_seed=dev,n_train=1000,n_valid=800,n_test=600)
        te=w["test"]
        for case,(testfault,validfault) in CASES.items():
            on,off=render_observed_v42(
                w,te,fault=testfault,seed=20264610+dev%101)
            model=(evidence/"REFERENCE_MODELS"/
                f"device{dev}_{validfault}_physical_reference_v42.json")
            for stress in MASKS:
                mo,mr=masks_v42(
                    on,off,stress,device_seed=dev,
                    mask_seed=20264650+REGISTERED_STRESS_ORDER.index(stress))
                if testfault=="no_reference":
                    mr[:,:,4:10]=False
                # Use ONLY measured samples. Any unknown TEST input
                # is NaN and cannot be supplied to downstream transform.
                x=np.asarray(on[:12]).copy()
                z=np.asarray(off[:12]).copy()
                a=mo[:12].copy();b=mr[:12].copy()
                x[~a]=np.nan;z[~b]=np.nan
                filename=f"device{dev}_{case}_{stress}"
                input_file=out/f"{filename}_external_observed_only.npz"
                np.savez_compressed(
                    input_file,on=x,off=z,observed_on=a,observed_off=b)
                json_file=out/f"{filename}_predictions.json"
                result=inference_physical_reference_npz_v42(
                    model_path=model,input_npz=input_file,
                    output_json=json_file)
                assert result["number_of_input_episodes"]==12
                prefix=f"device{dev}_{case}_{stress}_"
                saved_q=source[prefix+"q"][:12]
                saved_pair=source[prefix+"selected_pair"][:12]
                saved_y=source[
                    prefix+"physical_reference_estimated_energy"][:12]
                saved_allow=source[
                    prefix+"physical_reference_allowed"][:12]
                saved_reason=source[
                    prefix+"physical_reference_reason"][:12]
                for i,entry in enumerate(result["episodes"]):
                    if entry["independent_reference_R_NOT_provided_at_inference"] is not True:
                        raise AssertionError("TEST reference leaked into runtime")
                    if entry["clinical_or_causal_claim"] is not False:
                        raise AssertionError("Unsupported physical causal claim")
                    if bool(saved_allow[i]) != entry[
                        "historically_calibrated_source_value_available"]:
                        raise AssertionError(
                            f"Reopened source rejected different episode: {filename}/{i}")
                    if str(saved_reason[i])!=entry["physical_reference_decision"]:
                        raise AssertionError(
                            f"Reopened source changed refusal reason: {filename}/{i}")
                    if bool(saved_allow[i]):
                        if str(saved_pair[i])!=entry["selected_real_ON_OFF_sensor_pair"]:
                            raise AssertionError("Reopened source selected different view pair")
                        diff=abs(float(saved_y[i])-
                            entry["model_estimated_physical_reference_energy"])
                        max_error=max(max_error,diff)
                    elif entry["model_estimated_physical_reference_energy"] is not None:
                        raise AssertionError("Unmeasured source has invented energy")
                if testfault=="no_reference":
                    assert result["physical_source_available_count"]==0
                if validfault=="off_drift":
                    assert result["physical_source_available_count"]==0
                entries.append({
                    "device_seed":dev,"case":case,"stress":stress,
                    "new_real_external_sensor_episodes":12,
                    "physical_reference_accepted":
                        result["physical_source_available_count"],
                    "not_supplied_oracle_H_S_Y_or_reference_R":True,
                    "runtime_model_reopened_from_unchanged_JSON":True,
                })
    if len(entries)!=4*len(CASES)*len(MASKS):
        raise AssertionError("Incomplete external inference QA scenarios")
    if max_error>1e-8:
        raise AssertionError(f"Saved and reopened research model disagree: {max_error}")
    summary={
        "status":"V42_EXTERNAL_SENSOR_NPZ_JSON_INFERENCE_PARITY",
        "n_external_saved_NPZ_to_JSON_calls":len(entries),
        "n_total_external_sensor_episodes":sum(
            a["new_real_external_sensor_episodes"] for a in entries),
        "max_abs_estimated_physical_reference_energy_difference":
            max_error,
        "no_hidden_oracle_source_truth_or_TEST_reference_in_runtime":True,
        "every_OFF_missing_or_VALID2_known_drift_output_refuses":True,
        "externally_assumed_ON_OFF_physical_reference":True,
        "research_only_not_clinical":True,
        "receipts":entries,
    }
    (out/"INFERENCE_PARITY_AUDIT.json").write_text(json.dumps(
        summary,indent=2,ensure_ascii=False,allow_nan=False))
    print(json.dumps({
        "event":"V42_EXTERNAL_INFERENCE_PARITY",
        "n_reloaded_real_user_path_calls":len(entries),
        "n_patient_sensor_episodes":summary["n_total_external_sensor_episodes"],
        "max_abs_physical_reference_estimation_difference":max_error,
    }),flush=True)
    return summary


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--evidence-dir",type=Path,required=True)
    p.add_argument("--out-dir",type=Path,required=True)
    args=p.parse_args()
    qa(args.evidence_dir,args.out_dir)
