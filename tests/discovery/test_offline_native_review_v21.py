"""V21: offline yes/no/unsure/artifact reviewer round and HMAC replay scope."""
import copy
import json
import numpy as np
import pytest
import torch

from conceptfan_discovery.provenance_data_v21 import (
    make_v21_provenance_cohort,CHANNELS,
)
from conceptfan_discovery.multiscale_physiology_v10 import MultiScaleDualProcessConceptFAN
from conceptfan_discovery.offline_native_review_v21 import (
    create_offline_native_review_packet,import_offline_native_review_answers,
    render_local_review_html,write_offline_review_page,
)
from conceptfan_discovery.expert_feedback_v16 import native_expert_loss


KEY=b"a-private-test-review-key-at-least-32-bytes"
OTHER_KEY=b"another-independent-private-review-signature-key"


def _scenario():
    cohort=make_v21_provenance_cohort("physical_predictive")
    torch.manual_seed(111)
    model=MultiScaleDualProcessConceptFAN(
        observable_loadings=np.eye(4,3),
        channels=CHANNELS,
        forecast_horizon=6,n_observation_concepts=2,
        adaptive_feature_gradients=True,scales=(1,4,12),
    )
    model.eval()
    return cohort.discovery.train,model


def _packet():
    train,model=_scenario()
    packet=create_offline_native_review_packet(
        model,train,candidate_id="train-only-sensor-test",
        concept_slot=2,channel_names=CHANNELS,
        private_key=KEY,cases_per_stratum=3,nonce="preregistered-mock-review",
    )
    return train,model,packet


def test_offline_packet_is_train_scoped_blind_signed_pseudonymous_and_reopenable(tmp_path):
    train,model,packet=_packet()
    assert packet["schema"]=="conceptfan_native_review_packet_v21_1"
    assert len(packet["cases"])==9
    assert len(set(item["token"] for item in packet["cases"]))==9
    payload=json.dumps(packet,ensure_ascii=False)
    for forbidden in ("oracle_states","future","risk_score","outcome_labels","reviewer_id"):
        assert forbidden not in payload
    assert "episode_id" not in payload
    assert packet["local_only_do_not_publish_patient_measurements"]
    assert packet["reviewer_not_shown_target_or_model_prediction"]
    assert len(packet["packet_signature"])==64
    html=render_local_review_html(packet)
    assert "Да" in html and "Нет" in html
    assert "Не уверен" in html and "Артефакт измерения" in html
    assert "<svg" not in html  # curves generated by offline script
    assert "fetch(" not in html and "XMLHttpRequest" not in html
    target=write_offline_review_page(packet,tmp_path/"synthetic_review.html")
    assert target.read_text(encoding="utf8")==html
    with pytest.raises(FileExistsError):
        write_offline_review_page(packet,target)


def test_offline_review_returns_actual_train_only_v16_native_feedback_gradient():
    train,model,packet=_packet()
    decisions=("yes","no","unsure","artifact")
    responses={
        "packet_signature":packet["packet_signature"],
        "answers":[
            {"token":item["token"],"decision":decisions[i%4],"confidence":1.}
            for i,item in enumerate(packet["cases"])
        ],
    }
    prepared,receipt=import_offline_native_review_answers(
        packet,responses,private_key=KEY,
        original_train_episode_ids=train.episode_ids,
        n_slots=3,n_steps=24,reviewer_id="local_research_clinician_token",
    )
    assert receipt["packet_signature_verified"]
    assert receipt["reviewed_cases"]==len(packet["cases"])
    assert receipt["feedback_audit"]["artifact"]==2
    assert receipt["feedback_audit"]["uncertain"]==2
    assert receipt["feedback_audit"]["accepted"]==5
    assert not receipt["no_real_clinician_verified_by_software"] is False
    assert all(row[0] in set(train.episode_ids) for row in prepared.accepted)
    x=torch.from_numpy(train.x)
    m=torch.from_numpy(train.mask)
    out=model(x,m,process_mask=m)
    loss,stats=native_expert_loss(
        out.physical,torch.from_numpy(train.episode_ids),prepared,
    )
    loss.backward()
    assert stats["supervised_slots"]==1
    assert float(loss.detach())>=0
    assert model.physical.feature_logits.grad is not None
    assert float(model.physical.feature_logits.grad.abs().sum())>0
    assert float(out.decomposition_error())<1e-6


def test_packet_tamper_wrong_secret_or_new_episode_is_rejected():
    train,model,packet=_packet()
    answer={
        "packet_signature":packet["packet_signature"],
        "answers":[{"token":packet["cases"][0]["token"],"decision":"yes"}],
    }
    with pytest.raises(ValueError,match="integrity"):
        changed=copy.deepcopy(packet)
        changed["cases"][0]["measured_series"][CHANNELS[0]]["values"][0]=123456.
        import_offline_native_review_answers(
            changed,answer,private_key=KEY,
            original_train_episode_ids=train.episode_ids,
            n_slots=3,n_steps=24,
        )
    with pytest.raises(ValueError,match="integrity"):
        import_offline_native_review_answers(
            packet,answer,private_key=OTHER_KEY,
            original_train_episode_ids=train.episode_ids,
            n_slots=3,n_steps=24,
        )
    with pytest.raises(ValueError,match="non-TRAIN"):
        import_offline_native_review_answers(
            packet,answer,private_key=KEY,
            original_train_episode_ids=np.arange(5000,5960),
            n_slots=3,n_steps=24,
        )


def test_duplicate_tokens_unknown_token_or_wrong_options_refused():
    train,model,packet=_packet()
    first=packet["cases"][0]["token"]
    def request(items):
        return import_offline_native_review_answers(
            packet,{"packet_signature":packet["packet_signature"],"answers":items},
            private_key=KEY,original_train_episode_ids=train.episode_ids,
            n_slots=3,n_steps=24,
        )
    with pytest.raises(ValueError,match="duplicate"):
        request([{"token":first,"decision":"yes"},{"token":first,"decision":"no"}])
    with pytest.raises(ValueError,match="unrecognized"):
        request([{"token":"evil","decision":"yes"}])
    with pytest.raises(ValueError,match="four-choice"):
        request([{"token":first,"decision":"definitely-disease"}])
    with pytest.raises(ValueError,match="confidence"):
        request([{"token":first,"decision":"yes","confidence":float("nan")}])
    with pytest.raises(ValueError,match="model"):
        import_offline_native_review_answers(
            packet,{"packet_signature":packet["packet_signature"],"answers":[]},
            private_key=KEY,original_train_episode_ids=train.episode_ids,
            n_slots=2,n_steps=24,
        )


def test_unsure_and_artifact_are_not_negative_native_labels():
    train,model,packet=_packet()
    answers=[
        {"token":case["token"],"decision":"artifact" if i%2 else "unsure"}
        for i,case in enumerate(packet["cases"])
    ]
    prepared,receipt=import_offline_native_review_answers(
        packet,{"packet_signature":packet["packet_signature"],"answers":answers},
        private_key=KEY,original_train_episode_ids=train.episode_ids,
        n_slots=3,n_steps=24,
    )
    assert len(prepared.accepted)==0
    assert receipt["feedback_audit"]["accepted"]==0
    x=torch.from_numpy(train.x[:24])
    mask=torch.from_numpy(train.mask[:24])
    out=model(x,mask,process_mask=mask)
    loss,stats=native_expert_loss(
        out.physical,torch.from_numpy(train.episode_ids[:24]),prepared,
    )
    assert float(loss)==0
    assert stats["supervised_slots"]==0
